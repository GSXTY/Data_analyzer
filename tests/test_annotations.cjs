const assert=require('node:assert/strict');
const {AnnotationModel}=require('../annotation-model.js');
const map=new Map(),storage={getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v)};
const meta={file_id:'file-one',name:'test.csv',start:'2026-01-01 00:00:00',rows:10,channels:['flow','pressure'],raw_duration:100,display_duration:100.9};
const model=new AnnotationModel(meta,storage);
const event={id:'one',start:2,end:12,type:'疑似暂停',note:'人工复核',mode:'raw',channels:['flow']};
model.save(event);assert.equal(model.items.length,1);
const reload=new AnnotationModel(meta,storage);reload.load();assert.equal(reload.items[0].end,12);
reload.save({...event,end:14});assert.equal(reload.items.length,1);assert.equal(reload.items[0].end,14);
for(const patch of [{end:1},{start:-1},{end:Infinity},{end:101},{mode:'bad'},{channels:[]},{channels:['unknown']},{note:'a'.repeat(2001)}])assert.throws(()=>reload.save({...event,...patch}));
reload.save({...event,id:'two',mode:'engineering',start:100,end:100.8});assert.equal(reload.items.length,2);
const other=new AnnotationModel({...meta,file_id:'other'},storage);other.load();assert.equal(other.items.length,0);
assert.throws(()=>other.import(reload.export()));
const packet=reload.export();reload.import(packet);assert.equal(reload.items.length,2);
assert.throws(()=>reload.import({...packet,events:[{...packet.events[0],note:'conflict'}]}));
reload.remove('one');assert.equal(reload.items.length,1);
const failed=new AnnotationModel(meta,{getItem(){return null},setItem(){throw Error('quota')}});
assert.throws(()=>failed.save(event));assert.equal(failed.items.length,0,'failed storage must not claim a successful save');
assert.throws(()=>reload.import({...packet,events:[event,{...event,id:'three',end:1}]}));assert.equal(reload.items.length,1,'invalid imports must be atomic');
console.log('PASS: create, edit, reload, file isolation, time modes, boundary validation, delete, import conflicts and storage rollback');
const {compareReviewed}=require('../annotation-model.js');
const base={...event,source:'detector',status:'candidate',updated_at:'now'};
const feedback={version:1,kind:'reviewed',file_id:meta.file_id,run_id:'run',reviewed_range:[0,50],automatic:{run_id:'run',file_id:meta.file_id,events:[base]},events:[{...base,start:3,status:'reviewed'}]};
assert.equal(compareReviewed(feedback,meta)[0].result,'边界调整');
assert.throws(()=>compareReviewed({...feedback,file_id:'other'},meta));
feedback.events=[{...base,status:'ignored'}];assert.match(compareReviewed(feedback,meta)[0].result,/已忽略/);
console.log('PASS: feedback comparison, immutable original range and cross-file rejection');
assert.doesNotThrow(()=>compareReviewed({...feedback,version:2,reviewed_types:['疑似暂停'],review_mode:'spot'},meta));
console.log('PASS: compact scoped v2 feedback remains readable alongside legacy v1');
